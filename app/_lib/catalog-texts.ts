/** Блок секции: абзацы, нумерованные этапы, маркированный список, критерии, характеристики, кнопка заявки. */
export type LandingBlock =
  | { kind: "text"; paragraphs: string[] }
  | { kind: "steps"; items: string[] }
  | { kind: "list"; items: string[] }
  | { kind: "criteria"; rows: { title: string; text: string }[] }
  /** Таблица «Характеристика / материал»: значение может быть в несколько строк. */
  | { kind: "specs"; head: [string, string]; rows: { label: string; value: string[] }[] }
  /** «Отримати консультацію» в таблице — кнопка формы заявки. */
  | { kind: "cta"; label: string };

/** Без title — «Вступ без заголовка» листа. */
export type LandingSection = { title?: string; blocks: LandingBlock[] };

export type LandingText = {
  title: string;
  description: string;
  /** H1 героя из двух частей: видимый текст «light bold» = ячейка A3. */
  h1: { light: string; bold: string };
  sections: LandingSection[];
  faq?: { title: string; items: { question: string; answer: string }[] };
  /** Секция после FAQ (листы «Каталог …»: «Потрібна допомога з вибором …?»). */
  closing?: LandingSection;
};

